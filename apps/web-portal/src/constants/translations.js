// Fallback resolver: returns localized string with graceful fallback to English or key
export const getTranslation = (langId, key, fallback = '') => {
  const langDict = TRANSLATIONS[langId];
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Try English fallback first for missing keys
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  // Then Hindi fallback
  if (TRANSLATIONS.hi && TRANSLATIONS.hi[key]) {
    return TRANSLATIONS.hi[key];
  }
  return fallback || key;
};
