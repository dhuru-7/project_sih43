// Fallback resolver: if a regional dialect has partial strings, inherit from Hindi/English
export const getTranslation = (langId, key, fallback = '') => {
  const langDict = TRANSLATIONS[langId] || TRANSLATIONS.hi || TRANSLATIONS.en;
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fallback to Hindi, then English
  if (TRANSLATIONS.hi && TRANSLATIONS.hi[key]) {
    return TRANSLATIONS.hi[key];
  }
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key];
  }
  return fallback || key;
};
